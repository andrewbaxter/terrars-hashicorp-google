pub struct BuildDataProjectService {
    pub tf_id: std::string::String,
    #[doc = ""]
    pub service: terrars::PrimField<std::string::String>,
}

impl BuildDataProjectService {
    pub fn build(self, stack: &mut terrars::Stack) -> DataProjectService {
        let out = DataProjectService(std::rc::Rc::new(DataProjectService_ {
            shared: stack.shared.clone(),
            tf_id: self.tf_id,
            data: std::cell::RefCell::new(DataProjectServiceData_ {
                depends_on: core::default::Default::default(),
                provider: std::option::Option::None,
                lifecycle: core::default::Default::default(),
                for_each: std::option::Option::None,
                id: core::default::Default::default(),
                project: core::default::Default::default(),
                service: self.service,
            }),
        }));
        stack.add_datasource(out.0.clone());
        out
    }
}

